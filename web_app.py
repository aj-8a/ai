def make_handler(model, lock):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format, *args):
            # Keep terminal output quiet; only localhost requests are served.
            return

        def send_json(self, status, payload):
            raw = json.dumps(payload).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(raw)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(raw)

        def do_GET(self):
            if urlparse(self.path).path != "/":
                self.send_error(404)
                return
            raw = PAGE.encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(raw)))
            self.send_header("Content-Security-Policy", "default-src 'self'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'self'")
            self.end_headers()
            self.wfile.write(raw)

        def do_POST(self):
            if urlparse(self.path).path != "/chat":
                self.send_error(404)
                return
            if self.client_address[0] not in {"127.0.0.1", "::1"}:
                self.send_json(403, {"error": "Only local connections are allowed."})
                return
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if length < 2 or length > 1_000_000:
                    raise ValueError("Request size must be between 2 bytes and 1 MB.")
                data = json.loads(self.rfile.read(length))
                message = data.get("message", "")
                if not isinstance(message, str) or not message.strip():
                    raise ValueError("Message cannot be empty.")
                if len(message) > 20_000:
                    raise ValueError("Message is too long (maximum 20,000 characters).")
                history = data.get("history", [])
                if not isinstance(history, list):
                    history = []
                messages = [{"role": "system", "content": SYSTEM_PROMPT}]
                for item in history[-12:]:
                    if isinstance(item, dict) and item.get("role") in {"user", "assistant"} and isinstance(item.get("content"), str):
                        messages.append({"role": item["role"], "content": item["content"][:20_000]})
                messages.append({"role": "user", "content": message})
                with lock:
                    result = model.create_chat_completion(
                        messages=messages, max_tokens=1024, temperature=0.7, top_p=0.9
                    )
                answer = result["choices"][0]["message"]["content"] or ""
                self.send_json(200, {"answer": answer.strip() or "(The model returned an empty response.)"})
            except (ValueError, json.JSONDecodeError) as exc:
                self.send_json(400, {"error": str(exc)})
            except Exception as exc:
                self.send_json(500, {"error": f"Local generation failed: {exc}"})

    return Handler


def main() -> int:
    parser = argparse.ArgumentParser(description="Local-only browser UI for Aajimin Offline AI.")
    parser.add_argument("--model", type=Path, required=True, help="path to local .gguf model")
    parser.add_argument("--host", default="127.0.0.1", help="defaults to localhost only")
    parser.add_argument("--port", type=int, default=7860)
    parser.add_argument("--context", type=int, default=4096)
    parser.add_argument("--threads", type=int, default=4)
    args = parser.parse_args()
    if args.host not in {"127.0.0.1", "localhost", "::1"}:
        parser.error("For privacy, the web UI only supports localhost binding.")
    if not 1 <= args.port <= 65535:
        parser.error("--port must be between 1 and 65535")
    try:
        model = load_model(args.model.expanduser(), args.context, args.threads)
    except (FileNotFoundError, RuntimeError) as exc:
        print(f"Setup error: {exc}", file=__import__("sys").stderr)
        return 2
    server = ThreadingHTTPServer((args.host, args.port), make_handler(model, threading.Lock()))
    print(f"Aajimin Offline AI is ready: http://127.0.0.1:{args.port}")
    print("Local model only. Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping Aajimin AI.")
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
